-- -----------------------------------------------------------------------------
-- 1. entry_history table
-- -----------------------------------------------------------------------------
-- Stores a point-in-time snapshot every time `done` or `attended` changes
-- for any (user_name, subject) pair. Used for trend charts and history drawer.
--
-- id            — surrogate PK, auto-generated by Postgres identity
-- user_name     — matches entries.user_name (no FK to keep history after deletes)
-- subject       — matches entries.subject
-- done          — value of entries.done at the moment of the change
-- attended      — value of entries.attended at the moment of the change
-- changed_at    — wall-clock timestamp (UTC) of the change; defaults to now()
-- -----------------------------------------------------------------------------
create table if not exists entry_history (
  id          bigint generated always as identity primary key,
  user_name   text        not null,
  subject     text        not null,
  done        int         not null,
  attended    int         not null,
  changed_at  timestamptz not null default now()
);

-- Index for the most common query pattern: history for one person (or one
-- person + one subject), sorted by time.
create index if not exists entry_history_user_subject_time_idx
  on entry_history (user_name, subject, changed_at desc);


-- -----------------------------------------------------------------------------
-- 2. Row Level Security for entry_history
-- -----------------------------------------------------------------------------
-- The trigger function runs as SECURITY DEFINER (see §3) so it bypasses RLS
-- when writing. Anonymous users can only SELECT — they cannot insert, update,
-- or delete history rows directly.
-- -----------------------------------------------------------------------------
alter table entry_history enable row level security;

-- Allow anyone (including unauthenticated / anon) to read history rows.
drop policy if exists "anon can select entry_history" on entry_history;
create policy "anon can select entry_history"
  on entry_history
  for select
  using (true);

-- No insert / update / delete policies for anon — only the trigger (SECURITY
-- DEFINER) may write to this table.


-- -----------------------------------------------------------------------------
-- 3. Trigger function: log_entry_history
-- -----------------------------------------------------------------------------
-- Fires AFTER INSERT OR UPDATE on `entries`.
-- Inserts a new history row whenever done or attended changes value.
-- Using SECURITY DEFINER so it can bypass the restrictive RLS above.
-- The function is owned by the database owner role (postgres), which has
-- full table access regardless of RLS.
-- -----------------------------------------------------------------------------
create or replace function log_entry_history()
returns trigger
language plpgsql
security definer          -- runs as the function owner (postgres), not the caller
set search_path = public  -- pin search_path to prevent search_path injection
as $$
begin
  -- On INSERT, always record the initial state.
  -- On UPDATE, only record when done or attended actually changed (skip no-op writes).
  if (TG_OP = 'INSERT')
     or (TG_OP = 'UPDATE' and (NEW.done <> OLD.done or NEW.attended <> OLD.attended))
  then
    insert into public.entry_history (user_name, subject, done, attended, changed_at)
    values (NEW.user_name, NEW.subject, NEW.done, NEW.attended, now());
  end if;

  return NEW;
end;
$$;

-- Attach the trigger to the entries table (drop first to make this re-runnable).
drop trigger if exists trg_log_entry_history on entries;

create trigger trg_log_entry_history
  after insert or update
  on entries
  for each row
  execute function log_entry_history();


-- -----------------------------------------------------------------------------
-- 4. Realtime publication for entry_history
-- -----------------------------------------------------------------------------
-- Adds entry_history to the existing supabase_realtime publication so the
-- front-end can subscribe to live updates via postgres_changes.
-- The `alter publication ... add table` call is idempotent on Supabase.
-- -----------------------------------------------------------------------------
alter publication supabase_realtime add table entry_history;


-- -----------------------------------------------------------------------------
-- 5. One-time backfill
-- -----------------------------------------------------------------------------
-- Inserts the current values of every entry as the very first history record,
-- timestamped at now() so the trend charts have at least one data point.
-- Safe to run multiple times — it only inserts; it does not deduplicate.
-- If you want a clean state, truncate entry_history first, then run this.
-- -----------------------------------------------------------------------------
insert into entry_history (user_name, subject, done, attended, changed_at)
select
  e.user_name,
  e.subject,
  e.done,
  e.attended,
  now() as changed_at
from entries e;

